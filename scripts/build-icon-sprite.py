#!/usr/bin/env python3
"""Build the icon sprite used by the portfolio's inline editor.

Reads every SVG under public/portfolio-assets/icons/ and emits
src/portfolio/icons-sprite.js, which the page injects as a hidden <svg> of
<symbol> definitions. Icon regions then reference a symbol with <use>, so
changing an icon is a single attribute write and no async fetching is needed
at render time.

Run:  python scripts/build-icon-sprite.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICON_DIR = os.path.join(ROOT, "public", "portfolio-assets", "icons")
OUT = os.path.join(ROOT, "src", "portfolio", "icons-sprite.js")

# folder -> human label for the picker
FOLDERS = {
    "": "Brand",
    "ai": "AI & tools",
}

# Filenames are slugs; the picker shows proper brand names.
LABELS = {
    "facebook": "Facebook",
    "linkedin": "LinkedIn",
    "github": "GitHub",
    "discord": "Discord",
    "slack": "Slack",
    "openai": "OpenAI",
    "claude-color": "Claude",
    "cloudflare": "Cloudflare",
    "codex": "Codex",
    "cursor": "Cursor",
    "expo": "Expo",
    "googlechrome": "Chrome",
    "googleplay": "Play Store",
    "hermes": "Hermes",
    "kimi-color": "Kimi",
    "n8n": "n8n",
    "namecheap": "Namecheap",
    "python": "Python",
    "qwen": "Qwen",
    "react": "React",
    "slack-color": "Slack",
    "tailwindcss": "Tailwind",
    "vite": "Vite",
    "zapier": "Zapier",
    "zhipu": "Zhipu",
}


def symbol_id(folder, stem):
    return "pi-" + (folder + "-" if folder else "") + stem


def read_svg(path):
    """Return (viewBox, innerMarkup) for an SVG file."""
    src = open(path, encoding="utf-8").read()
    m = re.search(r"<svg\b[^>]*>", src)
    if not m:
        return None, None
    tag = m.group(0)
    vb = re.search(r'viewBox="([^"]+)"', tag)
    viewbox = vb.group(1) if vb else "0 0 24 24"
    inner = src[m.end():src.rfind("</svg>")]
    # Drop the <title> — it becomes a tooltip that would clash with the picker.
    inner = re.sub(r"<title>.*?</title>", "", inner, flags=re.S)
    return viewbox, inner.strip()


def main():
    icons = []
    for folder, label in FOLDERS.items():
        d = os.path.join(ICON_DIR, folder) if folder else ICON_DIR
        if not os.path.isdir(d):
            continue
        for name in sorted(os.listdir(d)):
            if not name.lower().endswith(".svg"):
                continue
            stem = name[:-4]
            viewbox, inner = read_svg(os.path.join(d, name))
            if not inner:
                print(f"  skip (no svg): {name}", file=sys.stderr)
                continue
            rel = os.path.join("icons", folder, name) if folder else os.path.join("icons", name)
            icons.append({
                "id": symbol_id(folder, stem),
                "name": stem,
                "label": LABELS.get(stem, stem.replace("-", " ").replace("_", " ").title()),
                "group": label,
                "path": rel.replace(os.sep, "/"),
                "viewBox": viewbox,
                "inner": inner,
            })

    lines = [
        "// Generated by scripts/build-icon-sprite.py — do not edit by hand.",
        "// Regenerate after adding or changing files under public/portfolio-assets/icons/.",
        "",
        "export const ICONS = [",
    ]
    for i in icons:
        lines.append("  {")
        lines.append(f"    id: '{i['id']}',")
        lines.append(f"    name: '{i['name']}',")
        lines.append(f"    label: '{i['label']}',")
        lines.append(f"    group: '{i['group']}',")
        lines.append(f"    path: '{i['path']}',")
        lines.append("  },")
    lines.append("]")
    lines.append("")
    lines.append("export const ICON_SPRITE = `<svg xmlns=\"http://www.w3.org/2000/svg\" style=\"display:none\" aria-hidden=\"true\">")
    for i in icons:
        lines.append(f"  <symbol id=\"{i['id']}\" viewBox=\"{i['viewBox']}\">{i['inner']}</symbol>")
    lines.append("</svg>`")
    lines.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print(f"wrote {OUT}: {len(icons)} icons")


if __name__ == "__main__":
    main()
